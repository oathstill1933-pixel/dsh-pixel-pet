"""Furniture source conversion only: shared framing, nearest sampling, 2x grid.

Art is generated by ImageGen; this script does not redraw or recolor the art.
Original RGBA sources remain unchanged in tools/source/codex/.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw,ImageFont

PACK=Path(__file__).resolve().parent.parent
SOURCE=PACK/'tools/source/codex'
LOGICAL=(180,150)
SIZE=(360,300)


def main():
    sources={name:Image.open(SOURCE/(name+'_00.png')).convert('RGBA') for name in ('empty','occupied')}
    boxes=[]
    for name,im in sources.items():
        a=np.array(im)
        ys,xs=np.where(a[:,:,3]>=128)
        boxes.append((int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)))
    if len({im.size for im in sources.values()})!=1:
        raise ValueError('Sources need the same canvas for shared framing')
    box=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
    width,height=box[2]-box[0],box[3]-box[1]
    factor=min(168/width,138/height)
    target=(round(width*factor),round(height*factor))
    offset=((LOGICAL[0]-target[0])//2,LOGICAL[1]-6-target[1])
    rendered={}
    for name,source in sources.items():
        im=source.crop(box).resize(target,Image.Resampling.NEAREST)
        a=np.array(im)
        a[:,:,3]=np.where(a[:,:,3]>=128,255,0)
        a[a[:,:,3]==0]=0
        im=Image.fromarray(a)
        logical=Image.new('RGBA',LOGICAL,(0,0,0,0))
        logical.paste(im,offset)
        native=logical.resize(SIZE,Image.Resampling.NEAREST)
        native.save(PACK/'sprites'/(name+'_00.png'))
        rendered[name]=native
        pixels=np.array(native)
        assert set(np.unique(pixels[:,:,3])) <= {0,255}
        assert not np.any(np.all(pixels[:,:,:3]==[255,0,255],axis=2)&(pixels[:,:,3]>0))
        assert np.array_equal(pixels,pixels[::2,::2].repeat(2,axis=0).repeat(2,axis=1))
    report={'canvas':list(SIZE),'logicalScale':2,'alpha':'binary 0/255','paletteReduced':False,
            'sourceCrop':list(box),'logicalArtSize':list(target),'logicalOffset':list(offset),
            'states':list(rendered),'sourceCanvases':{n:list(im.size) for n,im in sources.items()}}
    (PACK/'conversion.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    preview=Image.new('RGBA',(1440,640),'#ebeef5')
    d=ImageDraw.Draw(preview)
    try:
        font=ImageFont.truetype('msyh.ttc',20)
    except OSError:
        font=ImageFont.load_default()
    for j,(name,im) in enumerate(rendered.items()):
        preview.alpha_composite(im.resize((720,600),Image.Resampling.NEAREST),(j*720,0))
        d.text((j*720+24,606),'空窝' if name=='empty' else '睡觉',fill='#59647c',font=font)
    preview.convert('RGB').save(PACK/'preview.png')
    page='''<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>鲸鱼小窝</title><style>*{box-sizing:border-box}body{margin:0;background:#ebeef5;color:#32394d;font:14px system-ui,'Microsoft YaHei',sans-serif;padding:24px}main{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:16px;max-width:1200px;margin:auto}figure{margin:0;border:1px solid #d5dae6;border-radius:14px;overflow:hidden}img{width:100%;display:block;image-rendering:pixelated}figcaption{padding:12px 18px;border-top:1px solid #d5dae6}@media(max-width:640px){main{grid-template-columns:1fr}}</style><main><figure><img src="sprites/empty_00.png"><figcaption>空窝</figcaption></figure><figure><img src="sprites/occupied_00.png"><figcaption>睡觉</figcaption></figure></main></html>'''
    (PACK/'preview.html').write_text(page,encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False))


if __name__=='__main__':
    main()
